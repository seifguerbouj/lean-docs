#!/usr/bin/env node
// lean-docs: keeps feature docs short, readable, portable and in step with the code. No dependencies, no AI.
//   lean-docs                                                 status: pages, coverage, stale docs, lint, in four lines
//   lean-docs [check] [--root .] [--keep-shape] <doc.md>...  fail docs that are bloated, unreadable, unportable or stale
//   lean-docs affected [--base <ref>] [--staged] [--strict] list docs whose code changed but the doc didn't
//   lean-docs index [dir]                                     print a table of every feature doc under dir
//   lean-docs coverage [dir] [--min <pct>]                    share of code files some doc covers, and the biggest gaps
//   lean-docs wiki [dir] [--out <dir>] [--format obsidian|notion] build the reader view of the pages for Confluence, Notion or a wiki
//   lean-docs relink [--record <publish.json>] <file>...     point page links at the published pages (second publishing pass)
//   lean-docs hook                                            Claude Code Stop hook: ask the agent once to update stale docs
import { readFileSync, writeFileSync, existsSync, realpathSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { resolve, join, basename, relative, sep, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

// A link reference definition: hidden in CommonMark and, unlike an HTML comment, valid MDX (Docusaurus 3).
const INDEX_MARK = '[//]: # (generated by lean-docs index)';
const isIndex = (text) => text.startsWith(INDEX_MARK) || text.startsWith('<!-- generated by lean-docs index -->'); // old marker
// The same invisible line ties a guide that keeps its own shape to its code, with no Code section:
// [//]: # (lean-docs-code: src/client.py Timeout Client.send, src/config/)
const CODE_MARK = /^\[\/\/\]: # \(lean-docs-code:(.*)\)\s*$/;

const MAX_LINES = 60; // non-blank lines outside diagrams and the Use it example
const MAX_EXAMPLE = 15; // lines in one Use it code block
const MAX_WORDS = 30; // per sentence
const MAX_CODE_NAMES = 3; // backticked names in one prose line
const ALLOWED = ['how it works', 'use it', 'terms', 'config', 'does not', 'breaks when', 'code'];
const REQUIRED = ['how it works', 'does not', 'breaks when', 'code']; // affected reads Code

const BANNED = [
  [/\bthis (document|doc|page|guide|section|readme) (describes|explains|covers|provides|outlines|contains|introduces|shows|gives|is about|will|aims)\b/i, 'introduction, start with what it does'],
  [/\b(future (work|improvements|enhancements|plans)|roadmap|next steps)\b/i, 'future work, put it in an issue'],
  [/\b(in summary|in conclusion|to summarize|to sum up)\b/i, 'summary, the page is the summary'],
  [/\b(it is (important|worth) (to note|noting)|note that|please note|as mentioned)\b/i, 'throat-clearing'],
  [/\b(robust|seamless(ly)?|powerful|comprehensive|cutting-edge|state-of-the-art|leverag(e|es|ed|ing)|effortless(ly)?|simply|easily|elegant(ly)?|intuitive(ly)?|blazing(ly)?|streamlined?|scalable|flexible|best-in-class|world-class)\b/i, 'filler word'],
];

// Plain CommonMark + GFM tables + mermaid survives GitHub, GitLab, Confluence, Notion, Docusaurus, MkDocs.
const PORTABILITY = [
  [/<\/?[a-z][\w-]*(\s[^>]*)?\/?>/i, 'raw HTML, not portable'],
  [/^\s*(:::|!!!|\?\?\?)|^\s*>\s*\[!\w+\]/, 'admonition syntax, not portable, write a plain sentence'],
  [/\[\^[^\]]+\]/, 'footnote, not portable'],
  [/<(?=[^A-Za-z\/\s])|\{/, 'bare < or { outside backticks fails MDX (Docusaurus): wrap it in backticks'],
  // A link to a page in the same folder is fine: docs sites render it and publish.md rewrites it.
  [/\]\((?!https?:|mailto:|#)(?![\w.-]+\.mdx?(#[^)]*)?\))[^)]*\)/, 'relative link breaks outside the repo, write the path in backticks'],
];

// ponytail: naive split, "e.g." counts as a break. Errs toward shorter sentences, which is the point.
const sentences = (s) => s.split(/[.!?](?:\s|$)/).map((x) => x.trim()).filter(Boolean);
const words = (s) => s.split(/\s+/).filter(Boolean).length;

export function check(text, { root, keepShape, file } = {}) {
  if (file && /(^|\/)overview\.mdx?$/.test(file)) keepShape = true; // the landing page has its own shape
  const lines = text.replace(/\r\n?/g, '\n').split('\n'); // Windows line endings
  const problems = [];
  const add = (line, msg) => problems.push({ line, msg });
  const shape = (line, msg) => keepShape || add(line, msg);

  // YAML frontmatter (Docusaurus, MkDocs, Backstage) is allowed and not counted.
  if (lines[0] === '---') {
    const end = lines.indexOf('---', 1);
    if (end > 0) lines.fill('', 0, end + 1);
  }

  let fence = null;
  let table = null;
  let lead = null; // first paragraph after the title
  let section = null;
  let counted = 0;
  let examples = 0; // code blocks under Use it
  const diagrams = { flow: 0, sequence: 0 };
  const sections = new Set();
  const explained = new Set(); // sections holding a diagram or a numbered list

  const endTable = () => {
    // Code is read by affected, so it stays a table even with one row.
    if (table && table.rows <= 1 && table.section !== 'code') add(table.start, `table with ${table.rows} row, write it as a sentence`);
    table = null;
  };

  lines.forEach((l, i) => {
    const n = i + 1;
    const f = l.match(/^\s*(```|~~~)\s*([\w-]*)/);
    if (fence) {
      if (f && f[1] === fence.mark && !f[2]) {
        if (fence.lang === 'mermaid') {
          const kind = checkMermaid(fence.body, fence.line, add);
          if (kind) { diagrams[kind]++; explained.add(section); }
        } else if (section === 'use it' && !keepShape) {
          if (++examples === 2) add(fence.line, 'one example in "## Use it": the common case; other settings go in "## Config"');
          const size = fence.body.filter((b) => b.trim()).length;
          if (size > MAX_EXAMPLE) add(fence.line, `example is ${size} lines, max ${MAX_EXAMPLE}: show the common call, not every option`);
        }
        fence = null;
      } else {
        fence.body.push(l);
        if (fence.lang !== 'mermaid' && section !== 'use it' && l.trim()) counted++; // an example costs no reading time
      }
      return;
    }
    if (f) { endTable(); fence = { mark: f[1], lang: f[2].toLowerCase(), line: n, body: [] }; return; }
    if (CODE_MARK.test(l)) return; // invisible, not prose
    if (l.trim()) counted++;

    const isRow = /^\s*\|/.test(l);
    if (isRow) {
      table ??= { start: n, rows: 0, sep: false, section };
      if (/^[\s|:-]+$/.test(l) && l.includes('---')) table.sep = true;
      else if (table.sep) table.rows++;
    } else endTable();

    const h = l.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
    if (h) {
      if (lead) lead.open = false;
      if (h[1].length === 1) return;
      const name = h[2].toLowerCase().replace(/[:.]$/, '');
      if (h[1].length === 2) {
        section = name;
        sections.add(name);
        if (!ALLOWED.includes(name)) shape(n, `section "${h[2]}" is not allowed (allowed: ${ALLOWED.join(', ')})`);
      } else shape(n, 'sub-heading, a one-page doc does not need them');
      return;
    }

    if (/^\s*\d+[.)]\s/.test(l)) explained.add(section);

    if (!lead && !sections.size && l.trim()) lead = { line: n, text: l, open: true };
    else if (lead?.open) l.trim() ? (lead.text += ' ' + l) : (lead.open = false);

    const prose = l.replace(/(`+)[\s\S]*?\1/g, 'x'); // code spans, including ``a `b` c``
    // Guides on a docs site (keep-shape) use its features: admonitions, HTML, links between pages.
    // Feature pages get copied to Confluence and Notion, so they can't.
    const unquoted = prose.replace(/"[^"]*"|“[^”]*”/g, 'x'); // a quoted phrase is a mention, not a use
    for (const [re, msg] of [...BANNED, ...(keepShape ? [] : PORTABILITY)]) {
      const m = (/^(raw HTML|relative link|bare)/.test(msg) ? prose : unquoted).match(re);
      if (m) add(n, `${msg} ("${m[0]}")`);
    }

    // Readability: tables and the Code section are reference, not prose.
    if (!isRow && section !== 'code') {
      const long = sentences(prose.replace(/^\s*([-*]|\d+[.)])\s+/, '')).find((s) => words(s) > MAX_WORDS);
      if (long) add(n, `${words(long)}-word sentence, max ${MAX_WORDS}: split it`);
      // Per sentence, as page.md says: a paragraph is one line, so counting per line punishes paragraphs.
      // A URL, a URL path (`/items/{id}`) or a status code (`307`) is an address or a value, not a code name.
      const names = Math.max(0, ...sentences(l.replace(/(`+)([\s\S]*?)\1/g, (m, q, c) => (/^\s*(https?:\/\/\S+|\/[\w.~{}:*\/-]*|\d{3})\s*$/.test(c) ? 'x' : '\u0000'))).map((t) => (t.match(/\u0000/g) || []).length));
      if (names > MAX_CODE_NAMES && !keepShape) add(n, `${names} code names in one sentence: say it in words, put the names in "## Code"`); // API guides list names
    }

    if (!keepShape && /`[\w.@\/-]+\.\w+:\d+(-\d+)?`/.test(l)) add(n, 'line numbers drift: name the file and the function instead');

    // A relative link that points at nothing (guides on a docs site may link to each other).
    if (root && file) {
      for (const [, href] of prose.matchAll(/\]\((?!https?:|mailto:|#)([^)\s]+)\)/g)) {
        const target = resolve(dirname(resolve(file)), decodeURIComponent(href.split('#')[0]));
        if (href.split('#')[0] && !existsSync(target)) add(n, `link to ${href} points at nothing`);
      }
    }

    if (root && !keepShape) { // guides name files in other repos and files the reader creates
      // ponytail: anything like `a/b.ext` is treated as a repo path; MIME types like `application/x.y` false-positive.
      for (const [, p] of l.matchAll(/`([\w.@-]+(?:\/[\w.@-]+)*\/[\w@-]+\.\w+)`/g)) {
        if (!existsSync(resolve(root, p))) add(n, `\`${p}\` does not exist, the doc is stale or invented`);
      }
    }
  });
  endTable();

  // A symbol named in a Code row that isn't in its file was renamed or misspelled. affected would
  // never flag the page for it again, so say so now.
  if (root) {
    for (const { path, symbols, marker, fromWhat = [] } of codeRows(text)) {
      const file = resolve(root, path);
      if (marker && !existsSync(file)) add(0, `\`${path}\` in the lean-docs-code line does not exist: moved or renamed?`);
      if (!symbols.length || !existsSync(file) || path.endsWith('/')) continue;
      let src = '';
      try { src = readFileSync(file, 'utf8'); } catch { continue; }
      for (const sym of symbols.filter((s) => !fromWhat.includes(s))) {
        if (!new RegExp('\\b' + escapeRe(sym) + '\\b').test(src)) add(0, `\`${sym}\` isn't in ${path}: renamed? This page won't go stale when that code changes`);
      }
    }
  }

  if (!keepShape) {
    // A file under a folder row is already covered by it; the extra row is noise.
    const rows = codeRows(text).map((r) => r.path);
    for (const p of rows) {
      const dir = rows.find((d) => d !== p && d.endsWith('/') && p.startsWith(d));
      if (dir) add(0, `\`${p}\` is inside \`${dir}\`, already in "## Code": drop one row`);
    }
    if (counted > MAX_LINES) add(0, `${counted} lines (diagrams not counted), max ${MAX_LINES}. If it needs a second page, it is two features.`);
    if (lead) {
      const count = sentences(lead.text).length;
      if (count > 2) add(lead.line, `opening is ${count} sentences, max 2`);
      const names = (lead.text.match(/`[^`]+`/g) || []).length;
      if (names > 1) add(lead.line, `opening has ${names} code names, max 1: say what it does in plain words`);
    } else add(0, 'missing an opening: one or two plain sentences under the title');
    for (const s of REQUIRED) if (!sections.has(s)) add(0, `missing "## ${s[0].toUpperCase() + s.slice(1)}" section`);
    if (sections.has('how it works') && !explained.has('how it works'))
      add(0, '"## How it works" needs a mermaid diagram, or numbered steps if there are three or fewer');
    if (diagrams.flow > 1 || diagrams.sequence > 1) add(0, 'more than one diagram of a kind: one flow, one sequence at most');
  }

  return problems.sort((a, b) => a.line - b.line);
}

const ARROW = /\s*(?:<?-->|<?==>|<?-\.->|---|--[^->|]+?-->|==[^=>]+?==>|-\.[^.]+?\.->)(?:\|[^|]*\|)?\s*/;

// Returns 'flow' or 'sequence' for a diagram worth drawing, null otherwise.
function checkMermaid(body, line, add) {
  const type = (body.find((l) => l.trim()) || '').trim().split(/\s/)[0];

  if (type === 'sequenceDiagram') {
    const msgs = body
      .map((l) => l.match(/^\s*([\w ]+?)\s*(?:--?>>|--?>|--?[x)])[+-]?\s*([\w ]+?)\s*:/))
      .filter(Boolean)
      .map((m) => [m[1].trim(), m[2].trim()]);
    const pairs = new Set(msgs.map(([a, b]) => `${a}>${b}`));
    const backAndForth = msgs.some(([a, b]) => a !== b && pairs.has(`${b}>${a}`));
    if (msgs.length >= 3 && backAndForth) return 'sequence';
    add(line, 'sequence diagram with no real back-and-forth, use a flowchart or a sentence');
    return null;
  }

  if (type !== 'flowchart' && type !== 'graph') {
    add(line, `"${type}" diagram, only flowchart and sequenceDiagram are allowed`);
    return null;
  }

  // GitHub's mermaid fails the whole diagram on ( ) inside an unquoted box label: A[call foo(x)].
  const box = /([\w-]+)(?:\[([^\]"]*[()][^\]]*)\]|\{([^}"]*[()][^}]*)\})/;
  const bad = body.map((l) => l.match(box)).find(Boolean);
  if (bad) add(line, `unquoted ( ) in a box label breaks the diagram on GitHub: write ${bad[1]}${bad[2] !== undefined ? `["${bad[2]}"]` : `{"${bad[3]}"}`}`);
  // Same for quotes inside edge text: A -- say "x" --> B, or A -->|say "x"| B.
  // A label is fine with no quotes, or fully wrapped in one pair of quotes.
  const badLabel = (t) => t.includes('"') && !/^"[^"]*"$/.test(t.trim());
  const badEdge = body.find((l) => [...l.matchAll(/--\s+([^>|]+?)\s+-->|\|([^|]*)\|/g)].some((m) => badLabel(m[1] ?? m[2])));
  if (badEdge) add(line, `quotes inside an edge label break the diagram on GitHub: use -->|"label"| with no quotes inside (${badEdge.trim().slice(0, 40)})`);

  const nodes = new Set();
  for (const l of body) {
    if (l.trim().startsWith('%%')) continue;
    const ids = l.split(ARROW).map((p) => p.trim().match(/^([\w-]+)/)?.[1]).filter(Boolean);
    if (ids.length >= 2) ids.forEach((id) => nodes.add(id));
  }
  if (nodes.size >= 3) return 'flow';
  add(line, `flow diagram with ${nodes.size} boxes, write one sentence`);
  return null;
}

// Paths a doc says it covers: backticked file or folder paths in its "## Code" section.
export function codePaths(text) {
  return [...new Set(codeRows(text).map((r) => r.path))];
}

// A path has a slash or a file extension. `Client.send` and `Type::method` are symbols, not paths.
const FILE_EXT = /\.(js|jsx|ts|tsx|mjs|cjs|py|go|rb|java|kt|rs|php|cs|swift|scala|c|cc|cpp|h|hpp|ex|exs|dart|vue|svelte|md|mdx|json|ya?ml|toml|txt|lock|html|css|scss|sh|sql|proto|graphql|env|tf|ini|cfg|xml|gradle)$/i;
const isPath = (t) => t.includes('/') || FILE_EXT.test(t);
// `SearchWorker::search`, `Client.send`, `Foo#bar` are matched by their last part, the name in the code.
const symbolName = (t) => t.replace(/\(\)$/, '').split(/::|\.|#/).pop();

// Rows of the "## Code" section: a path, plus any functions or classes named in the same cell
// ("`src/client.py` `send`, `retry`"). With symbols, only changes to those symbols make the page stale.
// "- `path` `sym`: what it does" → "- `path` `sym`". Cuts at the first ": " outside backticks.
function whereOfListItem(l) {
  let inCode = false;
  for (let i = 0; i < l.length; i++) {
    if (l[i] === '`') inCode = !inCode;
    else if (!inCode && l[i] === ':' && (l[i + 1] === ' ' || i === l.length - 1)) return l.slice(0, i);
  }
  return l;
}

export function codeRows(text) {
  // A "## Code" inside a code fence (a page template, an example) isn't this page's Code section.
  const lines = text.replace(/\r\n?/g, '\n').replace(/^(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\1\s*$/gm, '').split('\n');
  const rows = [];
  const add = (tokens, extra, what = []) => {
    tokens = tokens.map((t) => t.replace(/:\d+(-\d+)?$/, '').replace(/^\.\//, ''));
    const symbols = tokens.filter((t) => !isPath(t)).map(symbolName).filter(Boolean);
    // A row naming functions also counts the ones only its What names: agents copy just the first few
    // into Where. check doesn't hold What to that (it can name a field or a type from elsewhere).
    const fromWhat = symbols.length ? [...new Set(what.filter((t) => !isPath(t) && /^[A-Za-z_$][\w$]*((::|\.|#)[\w$]+)*(\(\))?$/.test(t)).map(symbolName))].filter((t) => !symbols.includes(t)) : [];
    for (const path of tokens.filter(isPath)) rows.push({ path, symbols: [...symbols, ...fromWhat], ...extra, ...(fromWhat.length && { fromWhat }) });
  };
  const start = lines.findIndex((l) => /^##\s+code\s*$/i.test(l));
  const end = lines.findIndex((l, i) => i > start && /^##\s/.test(l));
  for (const l of start < 0 ? [] : lines.slice(start + 1, end < 0 ? undefined : end)) {
    const table = l.trim().startsWith('|'), cell = table ? l.split('|')[1] : whereOfListItem(l); // the "Where" part
    const ticked = (t) => [...t.matchAll(/`([^`\s]+)`/g)].map((m) => m[1]);
    add(ticked(cell), undefined, ticked(table ? l.split('|')[2] ?? '' : l.slice(cell.length)));
  }
  // Each comma-separated item of a lean-docs-code line is a path and its symbols, backticks optional.
  for (const l of lines) {
    const m = l.match(CODE_MARK);
    if (m) for (const item of m[1].split(',')) add(item.replace(/`/g, ' ').split(/\s+/).filter(Boolean), { marker: true });
  }
  return rows;
}

// A feature page has a Code section; a guide tied to code only by a lean-docs-code line keeps its shape.
const isGuide = (rows) => rows.length > 0 && rows.every((r) => r.marker);

const covers = (path, file) => file === path || file.startsWith(path.endsWith('/') ? path : path + '/');

// Docs whose covered code changed while the doc itself did not.
// `ok` holds docs a commit marked as checked ("lean-docs-ok: <doc>" or "lean-docs-ok: all").
const escapeRe = (t) => t.replace(/[.*+?^$()|[\]\\{}]/g, '\\$&');

// A call doesn't change what a page says about a name, so `send(`, `x.send` and `send.x` don't count,
// unless they are on a hunk's first line or its first line past a doc comment (the enclosing function
// or statement), or follow a definition keyword (`def send(`). Any other mention does: `send =`, `has_many :send`, a comment.
// Nor does a parameter or a labelled argument of that name (`(_ send: Msg)`, `for: send,`), even on a
// first line; a key holding a function (`send: () =>`), a Ruby `:send` and a declared property
// (`(val send: Int)`, `(private send: T)`) still count.
// ponytail: Ruby's paren-less calls (`send << x`), Python kwargs (`send=x`) and bare arguments (`f(a, send)`)
// still count: an isinstance(x, Timeout) in Timeout's own method was a real flag.
const DEF = '\\b(def|fun|func|fn|function|class|val|var|let|const|sub|module|struct|enum|interface|type|trait|object)\\s+(\\([^)]*\\)\\s*)?[*&]?([\\w$]+\\.)?';
// A name taken from a What cell (`fromWhat`) only counts as the enclosing function (the first line of a
// hunk past its doc comment) or after a definition keyword: What also holds example values like `a.b`.
const defines = (diff, sym, fromWhat) => {
  const s = escapeRe(sym), word = new RegExp('\\b' + s + '\\b');
  diff = diff.replace(new RegExp('([(,]\\s*(?:(?!(?:val|var|let|const|private|public|protected|internal|readonly|override|open|final)\\b)\\w+\\s+)?)' + s + '(?=\\s*:(?!:))(?!\\s*:\\s*(?:async\\b|function\\b|\\())|(\\w:\\s*)' + s + '(?=\\s*[,)])', 'g'), '$1$2 ');
  const hunks = diff.split(/^@@.*\n/m).slice(1).map((h) => h.split('\n'));
  // C, Java: `int send(` follows its doc comment; Dart, Java: `void send(` follows `@override`.
  const fn = (h) => h.find((l) => !/^.\s*(\/\/|\/\*|\*|#|@[\w.]+(\(.*\))?\s*$|$)/.test(l)) ?? '';
  if (fromWhat) return hunks.some((h) => word.test(fn(h))) || new RegExp(DEF + s + '\\b').test(diff);
  const firsts = hunks.flatMap((h) => [h[0], fn(h)]);
  const notCalls = diff.replace(new RegExp('(\\.|::|->)\\s*' + s + '\\b|\\b' + s + '\\s*[(.]', 'g'), ' ');
  return firsts.some((l) => word.test(l)) || new RegExp(DEF + s + '\\b').test(diff) || word.test(notCalls);
};

// A flag is likely real when the changed lines share a camelCase or snake_case name, a string or a number
// of 2+ digits with the page outside its Code section; otherwise it is a "check". On 30 Cobra commits the
// likely ones were 11 real of 22 and the checks 2 of 45. Both still count as stale.
// ponytail: a word match, not a parser; plain lowercase names (`args`, `path`) match prose, so they don't count.
// A changed line that mentions deprecation (`@deprecated use y`) is likely too: readers need it, and it rarely shares a name.
// ponytail: any /deprecat/i on a changed line, so un-deprecating or a typo fix in such a comment also counts; parse the tag if that gets noisy.
const STR = /"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'/g;
function shares(text, code) {
  if (/deprecat/i.test(code)) return true;
  const ls = text.split('\n'), s = ls.findIndex((l) => /^##\s+code\s*$/i.test(l)), e = ls.findIndex((l, i) => i > s && /^##\s/.test(l));
  const page = (s < 0 ? ls : [...ls.slice(0, s), ...(e < 0 ? [] : ls.slice(e))]).filter((l) => !CODE_MARK.test(l)).join('\n');
  if ([...code.matchAll(STR)].some((m) => (m[1] ?? m[2]).replace(/%\w|\\./g, '').trim().length >= 3 && page.includes(m[1] ?? m[2]))) return true;
  code = code.replace(STR, ' ');
  const nums = (code.match(/\b\d+(\.\d+)?\b/g) ?? []).filter((n) => n.length >= 2);
  const names = (code.match(/[A-Za-z_$][\w$]{2,}/g) ?? []).filter((t) => /[a-z0-9][A-Z]|_\w/.test(t));
  return nums.some((n) => new RegExp('(?<![\\w.])' + escapeRe(n) + '(?![\\w.])').test(page))
    || names.some((t) => new RegExp('(?<![\\w$])' + escapeRe(t) + '(?![\\w$])').test(page));
}

// `diffOf(file)` returns the change to a file with whole-function context, or null when it was only
// reformatted or had comments edited; rows that name symbols only count when it mentions one of them other than as a call.
export function affected(docs, changed, ok = new Set(), diffOf = () => '') {
  const touched = new Set(changed);
  const changedSyms = (row, file) => row.symbols.filter((sym) => defines(diffOf(file), sym, row.fromWhat?.includes(sym)));
  const hits = (row, file) => covers(row.path, file) && diffOf(file) !== null && (!row.symbols.length || changedSyms(row, file).length > 0);
  return docs
    .filter((d) => !touched.has(d.file) && !ok.has(d.file) && !ok.has('all'))
    .map((d) => {
      const rows = d.rows ?? d.paths.map((path) => ({ path, symbols: [] }));
      const because = changed.filter((c) => rows.some((r) => hits(r, c)));
      // Which named functions changed, so the reader knows which part of the page to fix.
      // A row without symbols covers the whole file, so then there's nothing narrower to say.
      const symbols = {};
      for (const f of because) {
        const matched = rows.filter((r) => hits(r, f));
        if (!matched.every((r) => r.symbols.length)) continue;
        const inContext = [...new Set(matched.flatMap((r) => changedSyms(r, f)))];
        // Prefer names on the changed lines themselves; the surrounding context can hold neighbours.
        const edited = diffOf(f).split('\n').filter((l) => /^[-+]/.test(l)).join('\n');
        const direct = inContext.filter((sym) => new RegExp('\\b' + escapeRe(sym) + '\\b').test(edited));
        symbols[f] = direct.length ? direct : inContext;
      }
      const r = Object.keys(symbols).length ? { file: d.file, because, symbols } : { file: d.file, because };
      if (typeof d.text === 'string') r.likely = shares(d.text, because.flatMap((f) => {
        const diff = diffOf(f) ?? '', mine = rows.filter((row) => hits(row, f));
        if (!diff.includes('@@')) return [diff]; // a new file counts in full
        return diff.split(/^(?=@@)/m).filter((h) => mine.some((row) => !row.symbols.length || row.symbols.some((sym) => defines(h, sym, row.fromWhat?.includes(sym)))))
          .map((h) => h.split('\n').filter(isChange).map((l) => l.slice(1)).join('\n'));
      }).join('\n'));
      return r;
    })
    .filter((d) => d.because.length);
}

