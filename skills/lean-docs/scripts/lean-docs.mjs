// git's --function-context reaches back to the last function line, so a change to a top-level const
// or an `if __name__` block pulled in the whole function above it. Each hunk now starts at the
// top-level statement holding its first change: a column-0 line after a blank line.
// ponytail: a column-0 line after a blank inside a multi-line string also counts as a start.
const fromChange = (diff) => diff.split(/^(?=@@)/m).map((hunk) => {
  const ls = hunk.split('\n');
  const first = ls.findIndex((l) => /^[-+]/.test(l));
  for (let i = first; i > 1; i--) if (/^.[A-Za-z_@#/]/.test(ls[i]) && /^.?\s*$/.test(ls[i - 1])) return [ls[0], ...inBlock(ls.slice(i))].join('\n');
  return [ls[0], ...inBlock(ls.slice(1))].join('\n');
}).join('\n'); // inBlock can drop a hunk's last newline; the next @@ must start a line

// A CLI keeps its commands in one block (`if (main) {`, `if __name__ == '__main__':`). git's function
// context for an edit there starts anywhere in that block, even at a blank line, and runs to its end, so
// every command's page matched. Inside a block, keep only the statements holding a change; a lone
// top-level `if`/`for`/... is unwrapped first. Comments and decorators belong to the statement below
// them; a line opening with `}`, `)`, `except` or `end` continues the one above, while `elif` starts its own.
// ponytail: indentation stands in for parsing; a multi-line string at column 0 turns it off.
const indent = (l) => l.slice(1).match(/^\s*/)[0].length;
const blank = (l) => !l.slice(1).trim();
const goesOn = (l) => /^.\s*([}\])]|(except|finally|rescue|ensure|catch|end)\b)/.test(l);
const isChange = (l) => /^[-+]/.test(l);
function inBlock(ls) {
  const heads = ls.filter((l) => !blank(l) && !goesOn(l));
  if (!heads.length) return ls;
  const top = Math.min(...heads.map(indent));
  const parts = [];
  let prefix = false;
  for (const l of ls) {
    if (!parts.length || (!blank(l) && !goesOn(l) && indent(l) === top && !prefix)) parts.push([]);
    parts.at(-1).push(l);
    if (!blank(l)) prefix = indent(l) === top && /^.\s*(@|#|\/\/|\/\*|\*)/.test(l);
  }
  if (top > 0) return parts.filter((p) => p.some(isChange)).flat();
  if (parts.filter((p) => p.some((l) => !blank(l))).length > 1) return ls;
  const h = ls.findIndex((l) => /^.(if|for|while|try|switch|with|do|unless)\b/.test(l));
  return h < 0 || ls.slice(0, h + 1).some(isChange) ? ls : [...ls.slice(0, h + 1), ...inBlock(ls.slice(h + 1))];
}

// A hunk that only re-indents or re-wraps code, or only edits comments, doesn't change what a page says,
// unless it deprecates something (`@deprecated` in a JSDoc is a real change). In Python only spacing
// inside a line can change, since indentation is code there. The old side (context and '-' lines) is
// compared with the new side (context and '+' lines), so a statement moved past an unchanged line counts.
// ponytail: a line guess, not a parser; a code line inside a block comment, a string starting with `* `
// or spaces inside a string literal count as cosmetic. `#` is a comment only before a space or `#`
// (keeps `#define`, `#[derive]`).
const COMMENT = /^\s*(\/\/|\/\*|\*\/|\*(\s|$)|#(\s|$|#))/;
function cosmetic(hunk, py) {
  const code = hunk.split('\n').slice(1).filter((l) => /^[-+ ]/.test(l) && l.slice(1).trim());
  if (code.some((l) => isChange(l) && /deprecat/i.test(l))) return false;
  const side = (sign) => code.filter((l) => l[0] !== sign && !COMMENT.test(l.slice(1))).map((l) => (py ? l.slice(1).match(/^\s*/)[0] : '') + l.slice(1).replace(/\s/g, '')).join(py ? '\n' : '');
  return side('+') === side('-');
}

// Python: git's function finder also matches a `def` inside a docstring's example code, so an edit in
// `include_router` was credited to `read_users` from its docstring, and the page naming include_router
// stayed quiet. Find the real enclosing def or class ourselves, skipping triple-quoted strings, and put
// it on the hunk's first line, which is where `defines` looks for the enclosing function.
export function pythonEnclosing(src, lineNo) {
  const ls = src.split('\n');
  // One pass over logical lines: a line starts a statement only outside strings and brackets.
  let quote = null, depth = 0;
  const starts = [], defs = [];
  ls.forEach((l, i) => {
    const starting = !quote && depth === 0;
    const ind = l.match(/^\s*/)[0].length;
    if (starting && l.trim() && !/^\s*#/.test(l)) {
      starts.push({ i, ind });
      const m = l.match(/^(\s*)(async\s+def|def|class)\s+\w/);
      if (m) defs.push({ i, ind, text: l });
    }
    // Strip strings and comments before counting brackets; a triple quote opens or closes a string across lines.
    let rest = l;
    while (rest) {
      if (quote) {
        const at = rest.indexOf(quote);
        if (at < 0) { rest = ''; break; }
        rest = rest.slice(at + 3); quote = null; continue;
      }
      const m = rest.match(/"""|'''|(["'])(?:\\.|(?!\1).)*\1|#.*|[()[\]{}]/);
      if (!m) break;
      if (m[0] === '"""' || m[0] === "'''") quote = m[0];
      else if ('([{'.includes(m[0])) depth++;
      else if (')]}'.includes(m[0])) depth = Math.max(0, depth - 1);
      rest = rest.slice(m.index + m[0].length);
    }
  });
  // A def's block runs to the line before the next statement indented no deeper than the def itself.
  for (const d of defs) {
    const next = starts.find((s) => s.i > d.i && s.ind <= d.ind && !/^\s*(\)|\]|\})/.test(ls[s.i]));
    d.end = next ? next.i - 1 : ls.length - 1;
  }
  const t = lineNo - 1;
  return defs.filter((d) => d.i <= t && t <= d.end).pop()?.text ?? null;
}
function withPythonDefs(d, src) {
  if (!src) return d;
  return d.split(/^(?=@@)/m).map((h) => {
    const m = h.match(/^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@/);
    if (!m) return h;
    const ls = h.split('\n');
    let n = +m[1] - 1, first = null;
    for (const l of ls.slice(1)) { if (l.startsWith('-')) { first ??= n + 1; continue; } n++; if (l.startsWith('+')) { first ??= n; break; } }
    const def = first && pythonEnclosing(src, first);
    return def && ls[1]?.slice(1) !== def ? [ls[0], ' ' + def, ...ls.slice(1)].join('\n') : h;
  }).join('');
}

function differ(cwd, { base, staged }) {
  const cache = new Map();
  const range = staged ? ['--cached'] : [branchBase(cwd, base) || tip(cwd)];
  return (file) => {
    if (!cache.has(file)) {
      let d = '';
      // Hunk headers name the function *before* the hunk, so they're dropped; --function-context already has the real one.
      try { d = git(['-c', `core.attributesFile=${driverAttributes()}`, '-c', `diff.leanjs.xfuncname=${JS_FUNCNAME}`, '-c', `diff.leanswift.xfuncname=${SWIFT_FUNCNAME}`, '-c', `diff.leandart.xfuncname=${DART_FUNCNAME}`, 'diff', '--function-context', ...range, '--', file], cwd).replace(/^(diff --git|index |--- |\+\+\+ ).*$/gm, '').replace(/^(@@[^@]*@@).*$/gm, '$1'); } catch {}
      // git gave a diff but every hunk was cosmetic: null, the file counts as unchanged (not as a new file to read whole).
      const gave = d.trim();
      d = d.split(/^(?=@@)/m).filter((h) => !h.startsWith('@@') || !CODE.test(file) || !cosmetic(h, file.endsWith('.py'))).join('');
      if (file.endsWith('.py') && d.trim()) {
        let src = '';
        try { src = staged ? git(['show', `:${file}`], cwd) : readFileSync(join(cwd, file), 'utf8'); } catch {}
        d = withPythonDefs(d, src);
      }
      d = fromChange(d);
      if (gave && !d.trim()) d = null;
      else if (!d.trim() && existsSync(join(cwd, file))) { try { d = readFileSync(join(cwd, file), 'utf8'); } catch {} }
      cache.set(file, d);
    }
    return cache.get(file);
  };
}

// "R100\told\tnew", "D\tpath", "M\tpath" → every path involved, plus a note for renames and deletions.
// --name-only would list only the new name of a renamed file, so pages covering the old one went unflagged.
export function parseNameStatus(text) {
  const files = [];
  const notes = new Map();
  for (const l of lines(text)) {
    const [status, a, b] = l.split('\t');
    if (status.startsWith('R') && b) { files.push(a, b); notes.set(a, `renamed to ${b}`); }
    else if (status === 'D') { files.push(a); notes.set(a, 'deleted'); }
    else if (a) files.push(a);
  }
  return { files, notes };
}

function changedFiles(cwd, { base, staged }) {
  const range = staged ? ['--cached'] : [branchBase(cwd, base) || tip(cwd)];
  const { files, notes } = parseNameStatus(git(['diff', '--name-status', '-M', ...range], cwd));
  const all = [...new Set([...files, ...(staged ? [] : lines(git(['ls-files', '-o', '--exclude-standard'], cwd)))])];
  all.notes = notes;
  return all;
}

