// How much of the code some doc's Code table covers, and the folders with the most uncovered files.
export function coverage(files, docs) {
  // A Docusaurus site in a subfolder (tRPC's www/) is the docs site's own code, not the product.
  const sites = files.flatMap((f) => f.match(/^(.+\/)docusaurus\.config\.\w+$/)?.[1] ?? []);
  const code = files.filter((f) => CODE.test(f) && !NOT_CODE.test(f) && !sites.some((s) => f.startsWith(s)));
  const isCovered = (f) => docs.some((d) => d.paths.some((p) => covers(p, f)));
  // Covered only by rows naming some functions (3 of a 6,500-line routing.py): counted, and reported as partial.
  const whole = (f) => docs.some((d) => (d.rows ?? d.paths.map((path) => ({ path, symbols: [] }))).some((r) => covers(r.path, f) && !r.symbols?.length));
  const gaps = new Map();
  let covered = 0, partial = 0;
  for (const f of code) {
    if (isCovered(f)) { covered++; if (!whole(f)) partial++; continue; }
    const dir = f.includes('/') ? f.slice(0, f.lastIndexOf('/') + 1) : './';
    gaps.set(dir, (gaps.get(dir) || 0) + 1);
  }
  return { total: code.length, covered, partial, gaps: [...gaps].sort((a, b) => b[1] - a[1]) };
}

// Files listed by more than one page with no symbols: any change to them flags all those pages.
export function sharedWithoutSymbols(docs) {
  const pages = new Map();
  for (const d of docs) for (const r of d.rows ?? []) {
    if (!r.symbols.length && !r.path.endsWith('/')) pages.set(r.path, [...(pages.get(r.path) ?? []), d.file]);
  }
  return [...pages].filter(([, files]) => new Set(files).size > 1);
}

// One row per lean feature doc: title, first sentence, file.
export function index(docs, dir = '') {
  const rows = docs
    .filter((d) => /^##\s+breaks when\s*$/im.test(d.text) && !isIndex(d.text))
    .map((d) => {
      const title = d.text.match(/^#\s+(.+)$/m)?.[1] ?? basename(d.file).replace(/\.mdx?$/, '');
      const lead = d.text.replace(/^---[\s\S]*?\n---\n/, '').split(/\n\s*\n/).find((p) => p.trim() && !/^\s*#/.test(p)) ?? '';
      const first = lead.replace(/\s+/g, ' ').trim().split(/(?<=[.!?])\s/)[0];
      // Links are relative to the index's folder, so pages in subfolders work.
      const link = dir && d.file.startsWith(dir + '/') ? d.file.slice(dir.length + 1) : basename(d.file);
      return `| [${title}](${link}) | ${first.replace(/\|/g, '\\|')} |`;
    })
    .sort();
  return `${INDEX_MARK}\n# Feature docs\n\n| Feature | What it does |\n|---|---|\n${rows.join('\n')}\n`;
}

// The wiki view: the same pages, rebuilt for readers who won't open the code (Confluence, Notion,
// a docs site). One source of truth stays in the repo; this is a projection, so it never drifts.
// Code tables and examples move to a "For engineers" section at the bottom; Terms become one
// glossary and every "Breaks when" table one troubleshooting page. An optional overview.md in the
// folder adds the system story and groups pages into areas.
const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[^\w\s-]/g, '').trim().replace(/[\s_]+/g, '-') || 'area';
function splitPage(text) {
  const body = text.replace(/\r\n/g, '\n').replace(/^---\n[\s\S]*?\n---\n/, '').replace(/^\[\/\/\]: # \(.*\)\n/gm, '');
  const parts = body.split(/^(?=## )/m);
  const head = parts.shift();
  const title = head.match(/^#\s+(.+)$/m)?.[1].trim() ?? '';
  const lead = head.replace(/^#\s+.+$/m, '').trim();
  const sections = new Map(parts.map((p) => [p.match(/^##\s+(.+)/)[1].trim().toLowerCase(), p.replace(/^##.*\n/, '').trim()]));
  return { title, lead, sections };
}
const tableRows = (md) => (md || '').split('\n').filter((l) => /^\s*\|/.test(l) && !/^[\s|:-]+$/.test(l)).slice(1)
  .map((l) => l.trim().replace(/^\||\|$/g, '').split(/(?<!\\)\|/).map((c) => c.trim()));

// One line of overview.md's "## Areas": "- **Matching** (owner: Jana, payments): [Partner matching](partner-matching.md), ..."
export function areaLine(l) {
  const m = l.match(/^\s*[-*]\s+\**([^:*(]+?)\**\s*(?:\(owner:\s*([^)]+)\))?\s*:\s*(.*)$/);
  return m && { name: m[1].trim(), owner: m[2]?.trim() || null, files: [...m[3].matchAll(/\]\(([^)#]+)/g)].map((x) => basename(x[1]).replace(/\.mdx?$/, '.md')) };
}
export function wiki(docs, { source = (f) => f, repo = '', branch = 'main' } = {}) {
  const pages = docs.filter((d) => /^##\s+breaks when\s*$/im.test(d.text) && !isIndex(d.text))
    .map((d) => ({ ...splitPage(d.text), file: basename(d.file).replace(/\.mdx?$/, '.md'), src: d.file }))
    .sort((a, b) => a.title.localeCompare(b.title));
  const ov = docs.find((d) => /(^|\/)overview\.mdx?$/.test(d.file));
  const out = [];
  const known = new Map(pages.map((p) => [p.file, p.title]));
  // "see retries.md" in plain text becomes a link; Notion would otherwise turn it into a web link.
  const linkBare = (body) => body.split(/(```[\s\S]*?```|`[^`\n]*`)/).map((part, i) => (i % 2 ? part
    : part.replace(/(?<![\w(\[\/.-])([\w-]+\.md)(?![\w)\]])/g, (m, f) => (known.has(f) ? `[${known.get(f)}](${f})` : m)))).join('');
  // The hash is of the docs a page is built from, not of the output: upgrading lean-docs mustn't make
  // every published page look behind. inputs defaults to the body (pages with no single source).
  const sha = (t) => createHash('sha1').update(t).digest('hex').slice(0, 12);
  const add = (file, title, parent, body, src = null, owner = null, inputs = null) => {
    const at = src && fileUrl(repo, branch, source(src));
    const head = [repo && (src ? (/^https?:/.test(at) ? `Generated from [${source(src)}](${at}). Edit it there; changes here are overwritten.` : `Generated from \`${at}\`. Edit it there; changes here are overwritten.`) : `Generated from the docs in \`${repo}\`; changes here are overwritten.`),
      owner && `Owner: ${owner}`].filter(Boolean).join('\n\n');
    body = linkBare([head, body].filter(Boolean).join('\n\n'));
    out.push({ file, title, parent, source: src && source(src), owner, body, hash: sha(`${title}\n${owner ?? ''}\n${inputs ?? body}`) });
  };

  // Areas from the overview's "## Areas" list: "- **Intake**: [Email intake](email-intake.md), ..."
  const areas = [];
  let overview = null;
  if (ov) {
    overview = splitPage(ov.text);
    for (const l of (overview.sections.get('areas') || '').split('\n')) {
      const m = areaLine(l);
      if (m) areas.push(m);
    }
  }
  const listed = new Set(areas.flatMap((a) => a.files));
  const rest = pages.filter((p) => !listed.has(p.file));
  if (areas.length && rest.length) areas.push({ name: 'Other features', files: rest.map((p) => p.file) });
  const firstSentence = (t) => t.replace(/\s+/g, ' ').split(/(?<=[.!?])\s/)[0];
  const list = (files) => files.map((f) => pages.find((p) => p.file === f)).filter(Boolean)
    .map((p) => `- [${p.title}](${p.file}): ${firstSentence(p.lead)}`).join('\n');

  const home = overview?.title || 'Feature docs';
  let homeBody = overview ? [overview.lead, overview.sections.has('how it fits together') && `## How it fits together\n\n${overview.sections.get('how it fits together')}`].filter(Boolean).join('\n\n') : 'What each part of the system does, how it works, and what to do when it goes wrong.';
  homeBody += areas.length ? '\n\n## Areas\n\n' + areas.map((a) => `- [${a.name}](area-${slug(a.name)}.md)`).join('\n') : '\n\n## Features\n\n' + list(pages.map((p) => p.file));
  homeBody += '\n\n## Reference\n\n- [Glossary](glossary.md): the terms these pages use\n- [Troubleshooting](troubleshooting.md): every known symptom, its likely cause and what to check';
  // With areas the overview lists area names only; without, it quotes every page's opening.
  add('overview.md', home, null, homeBody, ov?.file, null, (ov?.text ?? '') + (areas.length ? '' : pages.map((p) => p.title + p.lead).join('\n')));

  for (const a of areas) add(`area-${slug(a.name)}.md`, a.name, 'overview.md', list(a.files), null, a.owner, a.files.map((f) => { const p = pages.find((x) => x.file === f); return p ? p.title + p.lead : f; }).join('\n'));
  const areaOf = (f) => areas.find((x) => x.files.includes(f));
  const parentOf = (f) => (areaOf(f) ? `area-${slug(areaOf(f).name)}.md` : 'overview.md');

  const glossary = new Map();
  for (const p of pages) {
    const s = p.sections;
    const terms = tableRows(s.get('terms'));
    for (const [term, meaning] of terms) {
      const k = term.replace(/`/g, '').toLowerCase();
      if (!glossary.has(k)) glossary.set(k, { term, meaning, pages: [] });
      glossary.get(k).pages.push(`[${p.title}](${p.file})`);
    }
    const parts = [p.lead];
    if (s.has('how it works')) parts.push(`## How it works\n\n${s.get('how it works')}`);
    if (s.has('config')) parts.push(`## Settings\n\n${s.get('config')}`);
    if (s.has('does not')) parts.push(`## Limits\n\nWhat it does not do:\n\n${s.get('does not')}`);
    if (s.has('breaks when')) parts.push(`## When something goes wrong\n\n${s.get('breaks when')}`);
    if (terms.length) parts.push(`Terms used here are explained in the [Glossary](glossary.md).`);
    const eng = [];
    if (s.has('use it')) eng.push(`How it's called:\n\n${s.get('use it')}`);
    const code = tableRows(s.get('code'));
    if (code.length) eng.push('Where it lives in the code:\n\n' + code.map(([w, what]) => `- ${w}${what ? `: ${what}` : ''}`).join('\n'));
    if (!repo) eng.push(`Source page: \`${source(p.src)}\`. Edit it there; this page is generated from it.`);
    parts.push(`## For engineers\n\n${eng.join('\n\n')}`);
    add(p.file, p.title, parentOf(p.file), parts.join('\n\n'), p.src, areaOf(p.file)?.owner, docs.find((d) => d.file === p.src).text);
  }

  const g = [...glossary.values()].sort((a, b) => a.term.replace(/`/g, '').localeCompare(b.term.replace(/`/g, ''), undefined, { sensitivity: 'base' }));
  add('glossary.md', 'Glossary', 'overview.md', g.length ? '| Term | Meaning | Used in |\n|---|---|---|\n' + g.map((t) => `| ${t.term} | ${t.meaning} | ${t.pages.join(', ')} |`).join('\n') : 'No page defines special terms.', null, null, pages.map((p) => p.title + (p.sections.get('terms') ?? '')).join('\n'));
  add('troubleshooting.md', 'Troubleshooting', 'overview.md', 'Every known symptom, grouped by feature. Each row says what you see, the likely cause, and what to check.\n\n' +
    pages.filter((p) => p.sections.has('breaks when')).map((p) => `## [${p.title}](${p.file})\n\n${p.sections.get('breaks when')}`).join('\n\n'), null, null, pages.map((p) => p.title + (p.sections.get('breaks when') ?? '')).join('\n'));
  return out;
}

// Owners from each docs folder's overview.md Areas list: { 'docs/features/x.md': 'Jana' }.
function ownersOf(cwd, docs) {
  const owners = {};
  for (const dir of new Set(docs.map((d) => dirname(d.file)))) {
    const f = join(cwd, dir, 'overview.md');
    if (!existsSync(f)) continue;
    for (const l of readFileSync(f, 'utf8').split('\n')) {
      const a = areaLine(l);
      if (a?.owner) for (const file of a.files) owners[`${dir}/${file}`] = a.owner;
    }
  }
  return owners;
}
const ownerTag = (owners, file) => (owners[file] ? ` (owner: ${owners[file]})` : '');

// The second publishing pass: once every page exists, point [x](page.md) links at the published
// pages, using the record's ids. Notion gets page mentions, other targets plain links.
// Records written by hand or by an older run may list pages as an array; accept both.
const recordPages = (rec) => (Array.isArray(rec?.pages) ? Object.fromEntries(rec.pages.map((p) => [p.file, p])) : rec?.pages ?? {});
export function relink(text, record) {
  const notionTarget = /notion/i.test(JSON.stringify(record.target ?? ''));
  const url = (r) => r.url ?? (notionTarget ? `https://www.notion.so/${String(r.id ?? r.pageId ?? r.page_id ?? '').replace(/-/g, '')}` : null);
  return text.replace(/\[([^\]]+)\]\(([\w.-]+\.md)(#[^)]*)?\)/g, (m, label, f) => {
    const r = recordPages(record)[f];
    const u = r && url(r);
    if (!u) return m;
    return notionTarget ? `<mention-page url="${u}">${label}</mention-page>` : `[${label}](${u})`;
  });
}

// A link to one file on the forge: GitHub and Gitea /blob/<branch>/, GitLab /-/blob/<branch>/, Bitbucket /src/<branch>/.
// A repo that's only a name (no web remote) gives the name and path, unlinked.
export function fileUrl(repo, branch, path) {
  if (!/^https?:\/\//.test(repo)) return `${repo}/${path}`;
  const b = encodeURIComponent(branch || 'main').replace(/%2F/g, '/');
  if (/gitlab/i.test(repo)) return `${repo}/-/blob/${b}/${path}`;
  if (/bitbucket\.org/i.test(repo)) return `${repo}/src/${b}/${path}`;
  return `${repo}/blob/${b}/${path}`;
}
function defaultBranch(cwd) {
  try { return git(['symbolic-ref', '--short', 'refs/remotes/origin/HEAD'], cwd).trim().replace(/^origin\//, ''); } catch {}
  try { return git(['rev-parse', '--abbrev-ref', 'HEAD'], cwd).trim(); } catch {}
  return 'main';
}

// Where readers find the source: the web address of origin, or the repo's name. Never a local path.
function repoName(cwd) {
  let url = '';
  try { url = git(['remote', 'get-url', 'origin'], cwd).trim().replace(/\.git$/, ''); } catch {}
  const ssh = url.match(/^git@([^:]+):(.+)$/);
  if (ssh) return `https://${ssh[1]}/${ssh[2]}`;
  if (/^https?:\/\//.test(url)) return url.replace(/\/\/[^@/]+@/, '//'); // drop any credentials
  return basename(url || cwd);
}
// Obsidian: folders are the tree, the file name is the title, [[wikilinks]] survive moving notes,
// and "For engineers" becomes a folded callout. Same pages, so the same rewrite rules apply.
const noteName = (t) => t.replace(/[\\/:*?"<>|#^[\]]/g, '-').trim();
export function obsidian(pages, { repo = '', branch = 'main' } = {}) {
  const byFile = Object.fromEntries(pages.map((p) => [p.file, p]));
  const pathOf = (p) => {
    const parent = p.parent && byFile[p.parent];
    if (p.file.startsWith('area-')) return `${noteName(p.title)}/${noteName(p.title)}.md`; // folder note
    if (parent && parent.file.startsWith('area-')) return `${noteName(parent.title)}/${noteName(p.title)}.md`;
    return `${noteName(p.title)}.md`;
  };
  return pages.map((p) => {
    let body = p.body.replace(/\[([^\]]+)\]\(([\w.-]+\.md)\)/g, (m, text, f) => {
      const t = byFile[f] && noteName(byFile[f].title);
      return !t ? m : t === text ? `[[${t}]]` : `[[${t}|${text}]]`;
    });
    body = body.replace(/^## For engineers\n\n([\s\S]*)$/m, (m, eng) => '> [!info]- For engineers\n' + eng.split('\n').map((l) => (l ? `> ${l}` : '>')).join('\n'));
    const front = ['---', p.source ? `source: "${repo ? fileUrl(repo, branch, p.source) : p.source}"` : null, 'generated-by: lean-docs', 'tags: [lean-docs]', '---'].filter(Boolean).join('\n');
    return { ...p, path: pathOf(p), body: `${front}\n\n${body}` };
  });
}

// Notion: its connector takes Notion-flavored markdown, where tables are <table> blocks, a toggle
// heading folds what's indented under it, and some characters must be escaped outside code.
// Outside code: escape Notion's markup characters, and put file names in code so Notion doesn't
// turn them into web links (.md, .py and .sh are country domains). Links are left alone.
const FILE_LIKE = /(?<![\w(\[\/.`-])((?:[\w-]+\/)*[\w-]+\.(?:mdx?|py|ts|tsx|js|mjs|sh|json|ya?ml|go|rs|rb|java|kt|cs|php|toml|ini|cfg))(?![\w\])])/g;
const notionText = (t) => t.split(/(`+[^`]*`+|\[[^\]]*\]\([^)]*\))/).map((part, i) => (i % 2 ? part
  : part.replace(/([$<>{}^~])/g, '\\$1').replace(FILE_LIKE, '`$1`'))).join('');
export function notion(pages) {
  return pages.map((p) => {
    const out = [];
    let fence = false;
    let table = null;
    const flush = () => {
      if (!table) return;
      out.push('<table header-row="true">', ...table.map((r) => `\t<tr>\n${r.map((c) => `\t\t<td>${notionText(c)}</td>`).join('\n')}\n\t</tr>`), '</table>');
      table = null;
    };
    let eng = false; // inside "For engineers": everything below is indented under the toggle heading
    for (const l of p.body.split('\n')) {
      const ind = eng && l ? '\t' : '';
      if (/^\s*(```|~~~)/.test(l)) { flush(); fence = !fence; out.push(ind + l); continue; }
      if (fence) { out.push(ind + l); continue; }
      if (/^\s*\|/.test(l)) {
        if (/^[\s|:-]+$/.test(l)) continue;
        (table ??= []).push(l.trim().replace(/^\||\|$/g, '').split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, '|')));
        continue;
      }
      flush();
      if (/^## For engineers\s*$/.test(l)) { eng = true; out.push('## For engineers {toggle="true"}'); continue; }
      out.push(ind + (/^#{1,4}\s/.test(l) ? l : notionText(l)));
    }
    flush();
    return { ...p, body: out.filter((l, i, a) => l.trim() || (a[i - 1] ?? '').trim()).join('\n') };
  });
}

